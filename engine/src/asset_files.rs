//! The files of the `assets/` folder, read from disk or from the copies compiled into the
//! binary.
//!
//! `build.rs` embeds every file under `assets/` (without the `client` feature, i.e. in the
//! headless server, only `tuning.ron`, `levels/` and `enemies/`), so the game and the dedicated
//! server run from an otherwise empty folder. An assets folder on disk ([`crate::assets_dir`])
//! still wins: a file there is read instead of the embedded copy, a file missing there falls
//! back to it, and [`list`] returns the union of both. Hot reload, the tuning editor and the
//! asset generators keep working on the folder on disk.
//!
//! Paths are relative to the assets folder, `/`-separated and made of plain names
//! (`levels/vestry.ron`). Anything else (`..`, `.`, absolute paths, `\`, drive letters) is
//! found nowhere ([`check_path`]): level and prop names can come from servers.

use std::borrow::Cow;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::sync::Once;

/// Every embedded file (path, contents), sorted by path. Generated by `build.rs`.
static EMBEDDED: &[(&str, &[u8])] = include!(concat!(env!("OUT_DIR"), "/embedded_assets.rs"));

/// Where a file was found.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Source {
    /// In the assets folder on disk.
    Disk(PathBuf),
    /// Compiled into the binary.
    Embedded(&'static [u8]),
}

/// Checks that `path` is a plain relative path inside the assets folder: `/`-separated names,
/// none of them empty, `.` or `..`, and no `\`, `:` or NUL.
pub fn check_path(path: &str) -> Result<(), String> {
    if path.is_empty() || path.contains(['\\', ':', '\0']) {
        return Err("not a plain relative path".into());
    }
    if path
        .split('/')
        .any(|name| name.is_empty() || name == "." || name == "..")
    {
        return Err("must be a relative path inside assets/ without '.' or '..'".into());
    }
    Ok(())
}

/// Finds `path`: the file in the assets folder on disk if there is one, else the embedded
/// copy. `None` if neither has it or the path isn't plain ([`check_path`]).
pub fn find(path: &str) -> Option<Source> {
    find_in(&disk_dir(), EMBEDDED, path)
}

/// Reads `path` from disk, else its embedded copy ([`find`]). The error names the path.
pub fn read(path: &str) -> anyhow::Result<Cow<'static, [u8]>> {
    read_in(&disk_dir(), EMBEDDED, path)
}

/// [`read`] as UTF-8 text.
pub fn read_to_string(path: &str) -> anyhow::Result<String> {
    let bytes = read(path)?;
    String::from_utf8(bytes.into_owned()).map_err(|_| anyhow::anyhow!("{path} is not UTF-8"))
}

/// Stems of the `*.{ext}` files directly in `dir` (`list("levels", "ron")` →
/// `["cistern_nine", ...]`): those on disk and the embedded ones, sorted, each once.
pub fn list(dir: &str, ext: &str) -> Vec<String> {
    list_in(Some(&disk_dir()), EMBEDDED, dir, ext)
}

/// The embedded copy of `path`, ignoring the folder on disk.
pub fn embedded(path: &str) -> Option<&'static [u8]> {
    lookup(EMBEDDED, path)
}

/// Stems of the embedded `*.{ext}` files in `dir`, sorted, ignoring the folder on disk.
pub fn embedded_list(dir: &str, ext: &str) -> Vec<String> {
    list_in(None, EMBEDDED, dir, ext)
}

/// [`crate::assets_dir`], logging once which one is used.
fn disk_dir() -> PathBuf {
    static LOGGED: Once = Once::new();
    let dir = crate::assets_dir();
    LOGGED.call_once(|| {
        if dir.is_dir() {
            let shown = std::path::absolute(&dir).unwrap_or_else(|_| dir.clone());
            log::info!(
                "assets: using {}, embedded copies for files missing there",
                shown.display()
            );
        } else {
            log::info!("assets: no assets folder on disk, using the embedded files");
        }
    });
    dir
}

type Table<'a> = &'a [(&'a str, &'a [u8])];

fn lookup<'a>(table: Table<'a>, path: &str) -> Option<&'a [u8]> {
    let i = table.binary_search_by_key(&path, |&(p, _)| p).ok()?;
    Some(table[i].1)
}

fn find_in(disk: &Path, table: Table<'static>, path: &str) -> Option<Source> {
    check_path(path).ok()?;
    let file = disk.join(path);
    if file.is_file() {
        return Some(Source::Disk(file));
    }
    lookup(table, path).map(Source::Embedded)
}

fn read_in(disk: &Path, table: Table<'static>, path: &str) -> anyhow::Result<Cow<'static, [u8]>> {
    check_path(path).map_err(|e| anyhow::anyhow!("{path:?}: {e}"))?;
    match find_in(disk, table, path) {
        Some(Source::Disk(file)) => std::fs::read(&file)
            .map(Cow::Owned)
            .map_err(|e| anyhow::anyhow!("reading {}: {e}", file.display())),
        Some(Source::Embedded(bytes)) => Ok(Cow::Borrowed(bytes)),
        None => anyhow::bail!(
            "{path} not found (neither in {} nor embedded)",
            disk.display()
        ),
    }
}

fn list_in(disk: Option<&Path>, table: Table, dir: &str, ext: &str) -> Vec<String> {
    let mut stems = BTreeSet::new();
    if check_path(dir).is_err() {
        return Vec::new();
    }
    let suffix = format!(".{ext}");
    let prefix = format!("{dir}/");
    for (path, _) in table {
        if let Some(name) = path.strip_prefix(&prefix)
            && !name.contains('/')
            && let Some(stem) = name.strip_suffix(&suffix)
        {
            stems.insert(stem.to_owned());
        }
    }
    let entries = disk.and_then(|d| std::fs::read_dir(d.join(dir)).ok());
    for entry in entries.into_iter().flatten().flatten() {
        let path = entry.path();
        if path.is_file()
            && path.extension().is_some_and(|e| e == ext)
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
        {
            stems.insert(stem.to_owned());
        }
    }
    stems.into_iter().collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A stand-in for the generated table (sorted by path).
    const TABLE: &[(&str, &[u8])] = &[
        ("levels/notes.txt", b"not a level"),
        ("levels/one.ron", b"embedded one"),
        ("levels/sub/deep.ron", b"nested"),
        ("levels/two.ron", b"embedded two"),
        ("tuning.ron", b"embedded tuning"),
    ];

    /// An assets folder on disk with `levels/two.ron` (overriding the embedded one),
    /// `levels/three.ron` (disk only), a non-level file and a file just outside it.
    fn disk_folder(name: &str) -> PathBuf {
        let base = std::env::temp_dir().join(format!("velocide-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&base);
        let assets = base.join("assets");
        std::fs::create_dir_all(assets.join("levels/three.ron.d")).unwrap();
        std::fs::write(assets.join("levels/two.ron"), b"disk two").unwrap();
        std::fs::write(assets.join("levels/three.ron"), b"disk three").unwrap();
        std::fs::write(assets.join("levels/readme.md"), b"hi").unwrap();
        std::fs::write(base.join("outside.ron"), b"secret").unwrap();
        assets
    }

    fn text(bytes: anyhow::Result<Cow<'static, [u8]>>) -> String {
        String::from_utf8(bytes.unwrap().into_owned()).unwrap()
    }

    #[test]
    fn disk_files_win_and_missing_ones_fall_back_to_the_embedded_copies() {
        let assets = disk_folder("asset-files-read");
        let read = |path: &str| read_in(&assets, TABLE, path);
        assert_eq!(text(read("levels/two.ron")), "disk two");
        assert_eq!(text(read("levels/three.ron")), "disk three");
        assert_eq!(text(read("levels/one.ron")), "embedded one");
        assert_eq!(text(read("tuning.ron")), "embedded tuning");
        assert_eq!(
            find_in(&assets, TABLE, "levels/two.ron"),
            Some(Source::Disk(assets.join("levels/two.ron")))
        );
        assert_eq!(
            find_in(&assets, TABLE, "levels/one.ron"),
            Some(Source::Embedded(b"embedded one"))
        );
        // A directory on disk is not a file: the embedded copy (or nothing) is used.
        assert_eq!(find_in(&assets, TABLE, "levels/three.ron.d"), None);

        let error = read("levels/missing.ron").unwrap_err().to_string();
        assert!(error.contains("levels/missing.ron"), "{error}");

        // No folder on disk at all: everything comes from the table.
        let nowhere = assets.join("does-not-exist");
        assert_eq!(
            text(read_in(&nowhere, TABLE, "levels/two.ron")),
            "embedded two"
        );
        assert!(read_in(&nowhere, TABLE, "levels/three.ron").is_err());
        std::fs::remove_dir_all(assets.parent().unwrap()).unwrap();
    }

    #[test]
    fn lists_are_the_union_of_disk_and_embedded() {
        let assets = disk_folder("asset-files-list");
        assert_eq!(
            list_in(Some(&assets), TABLE, "levels", "ron"),
            ["one", "three", "two"]
        );
        assert_eq!(list_in(None, TABLE, "levels", "ron"), ["one", "two"]);
        assert_eq!(list_in(Some(&assets), TABLE, "levels", "txt"), ["notes"]);
        assert_eq!(list_in(Some(&assets), TABLE, "levels/sub", "ron"), ["deep"]);
        let nowhere = assets.join("does-not-exist");
        assert_eq!(
            list_in(Some(&nowhere), TABLE, "levels", "ron"),
            ["one", "two"]
        );
        assert!(list_in(Some(&assets), TABLE, "../assets/levels", "ron").is_empty());
        std::fs::remove_dir_all(assets.parent().unwrap()).unwrap();
    }

    #[test]
    fn only_plain_relative_paths_are_found() {
        let assets = disk_folder("asset-files-paths");
        for evil in [
            "",
            "/etc/passwd",
            "../outside.ron",
            "levels/../../outside.ron",
            "levels/../tuning.ron",
            "./tuning.ron",
            "levels//two.ron",
            "levels/",
            "levels\\two.ron",
            "..\\outside.ron",
            "C:/outside.ron",
            "C:outside.ron",
            "tuning.ron\0",
        ] {
            assert!(check_path(evil).is_err(), "{evil:?} must be refused");
            assert_eq!(find_in(&assets, TABLE, evil), None, "{evil:?}");
            assert!(read_in(&assets, TABLE, evil).is_err(), "{evil:?}");
        }
        assert_eq!(check_path("levels/two.ron"), Ok(()));
        std::fs::remove_dir_all(assets.parent().unwrap()).unwrap();
    }

    #[test]
    fn the_embedded_table_is_sorted_and_holds_what_the_simulation_reads() {
        assert!(EMBEDDED.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(EMBEDDED.iter().all(|(path, _)| check_path(path).is_ok()));
        assert!(embedded("tuning.ron").is_some_and(|t| !t.is_empty()));
        assert!(embedded_list("levels", "ron").len() >= 2);
        assert!(embedded_list("enemies", "ron").contains(&"gnawer".to_owned()));
        // Models and shaders only in builds that render.
        let has = |dir: &str| EMBEDDED.iter().any(|(p, _)| p.starts_with(dir));
        assert_eq!(has("models/"), cfg!(feature = "client"));
        assert_eq!(has("shaders/"), cfg!(feature = "client"));
    }
}
